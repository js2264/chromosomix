/**
 * A selection of genomes is drawn *as* genomes.
 *
 * Three pictures, one rule, and until now the middle one broke it. The
 * whole-metagenome view divides and labels its axis by genome, because 20,000
 * contig hairlines over the blocks that are the point are a grey wash
 * (`ui/MatrixPanel.separatorsFor`). One genome opened on its own divides by
 * contig, because its contigs are the only structure inside it. And ticking
 * four MAGs out of two thousand — the picture between those two — divided by
 * *contig*, so the four blocks a reader ticked four boxes to see had two
 * thousand lines across them and no line where one genome ended and the next
 * began.
 *
 * Two things had to be true for that to be fixed rather than papered over, and
 * they are the two halves of this file:
 *
 *  - the reader has to *say* the genome runs are the boundaries — that is
 *    `selectionDrawsGenomes`, and it is a decision about what was ticked rather
 *    than about what the file holds;
 *  - and where the axis is pooled, a cell may not straddle two genomes — that
 *    is `selectionPooling`'s group argument. A boundary drawn on an axis whose
 *    cells mix two MAGs is a boundary a cell late, and the block it closes
 *    contains a sliver of the next genome.
 *
 * No fixture: both are arithmetic, and the file that would provide the genomes
 * is generated by a Python package a fresh clone has not got.
 */

import { describe, expect, it } from 'vitest'

import { IDENTITY_PLAN, selectionPooling } from '@/metacooler/pooling'
import { selectionDrawsGenomes } from '@/worker/groups'
import { separatorsFor } from '@/ui/MatrixPanel'
import type { AxisGroup, MatrixResult } from '@/worker/protocol'

const run = (label: string, start: number, end: number): AxisGroup => ({ label, start, end })

describe('selectionDrawsGenomes', () => {
  it('divides by genome when several genomes were ticked', () => {
    expect(selectionDrawsGenomes('genome', [run('MAG_7', 0, 40), run('MAG_12', 40, 90)])).toBe(true)
  })

  it('keeps the contig lines for one genome, which has nothing coarser', () => {
    expect(selectionDrawsGenomes('genome', [run('MAG_7', 0, 40)])).toBe(false)
  })

  it('keeps the contig lines when contigs were ticked, whatever they came from', () => {
    // The choice *was* the contigs: their names are the answer to "what did I
    // pick", and coarsening to the genomes behind them would lose it.
    expect(selectionDrawsGenomes('contig', [run('MAG_7', 0, 3), run('MAG_12', 3, 5)])).toBe(false)
  })

  it('has nothing to draw on a plain cooler, which has no genomes', () => {
    expect(selectionDrawsGenomes('genome', undefined)).toBe(false)
  })
})

describe('the separators a ticked selection of genomes gets', () => {
  // Two MAGs of three contigs each, as the reader sends them: contig runs for
  // the tooltip and the coordinates, genome runs over them.
  const contigs: AxisGroup[] = [
    run('c1', 0, 10),
    run('c2', 10, 18),
    run('c3', 18, 30),
    run('c4', 30, 41),
    run('c5', 41, 50),
    run('c6', 50, 60),
  ]
  const genomes: AxisGroup[] = [run('MAG_7', 0, 30), run('MAG_12', 30, 60)]
  const block = (extra: Partial<MatrixResult> = {}): MatrixResult =>
    ({
      nrows: 60,
      ncols: 60,
      values: new Float32Array(0),
      rowExtent: [0, 60],
      colExtent: [0, 60],
      rowGroups: contigs,
      colGroups: contigs,
      rowGenomes: genomes,
      colGenomes: genomes,
      level: 'bin',
      ...extra,
    }) as MatrixResult

  it('draws and labels the genomes, not the contigs inside them', () => {
    const set = separatorsFor(block({ genomeBoundaries: true }))
    expect(set.rows.map((s) => s.at)).toEqual([0, 30])
    expect(set.rows.map((s) => s.label)).toEqual(['MAG_7', 'MAG_12'])
    expect(set.cols.map((s) => s.label)).toEqual(['MAG_7', 'MAG_12'])
    // The heavier stroke lands on the same coordinates, by the same array — the
    // renderer skips the fine pass when it recognises the identity.
    expect(set.groupRows).toBe(set.rows)
    expect(set.groupCols).toBe(set.cols)
  })

  it('leaves a selection the reader did not mark alone', () => {
    // Ticked contigs, or one genome: the genome runs are still sent, for the
    // tooltip, and still are not lines.
    const set = separatorsFor(block())
    expect(set.rows.map((s) => s.at)).toEqual([0, 10, 18, 30, 41, 50])
    expect(set.groupRows).toBeUndefined()
    expect(set.groupCols).toBeUndefined()
  })
})

describe('pooling a selection of genomes', () => {
  // Six one-bin contigs: three of MAG_7, three of MAG_12. Small enough that the
  // cells have to hold whole contigs, which is the only regime where a cell can
  // straddle anything.
  const units = Array.from({ length: 6 }, (_, id) => ({ id, extent: [id, id + 1] as [number, number] }))
  const genomeOf = Int32Array.from([0, 0, 0, 1, 1, 1])

  /** The genomes each output cell ended up holding. */
  const cellGenomes = (pooling: ReturnType<typeof selectionPooling>): number[][] =>
    Array.from({ length: pooling.ids.length }, (_, cell) =>
      [
        ...new Set(
          Array.from(
            pooling.members.slice(pooling.memberStart[cell], pooling.memberStart[cell + 1]),
            (contig) => genomeOf[contig],
          ),
        ),
      ].sort(),
    )

  it('never puts two genomes in one cell', () => {
    const pooling = selectionPooling(6, units, IDENTITY_PLAN, 3, genomeOf)
    // Three cells were allowed and only two are wanted: the capacity widens
    // until each genome's contigs fit a cell of their own.
    expect(pooling.ids.length).toBe(2)
    expect(cellGenomes(pooling)).toEqual([[0], [1]])
    // And the cells are the genome blocks, so a boundary drawn at cell 1 is the
    // boundary between the two MAGs and not one contig past it.
    expect([...pooling.slot]).toEqual([0, 0, 0, 1, 1, 1])
  })

  it('straddles them without the grouping, which is the boundary being wrong', () => {
    // The same selection, unguarded: contig 2 (MAG_7) shares a cell with contig
    // 3 (MAG_12). Pinned so the guarantee above is read as a guarantee rather
    // than as a property of these six numbers.
    const pooling = selectionPooling(6, units, IDENTITY_PLAN, 3)
    expect(pooling.ids.length).toBe(3)
    expect(cellGenomes(pooling)).toEqual([[0], [0, 1], [1]])
  })

  it('leaves an axis that needs no pooling exactly as it was', () => {
    // Room for every contig: the grouping changes nothing, because nothing
    // shares a cell for it to keep apart.
    const pooling = selectionPooling(6, units, IDENTITY_PLAN, 6, genomeOf)
    expect(pooling.ids.length).toBe(6)
    expect(pooling.contigsPerCell).toBe(1)
    expect([...pooling.ids]).toEqual([0, 1, 2, 3, 4, 5])
  })
})
