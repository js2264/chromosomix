/**
 * Plain cooler files, opened as themselves (spec §9).
 *
 * A `.cool` has `/chroms`, `/bins`, `/pixels` and `indexes/chrom_offset` and
 * nothing else this viewer needs: every coordinate is bin arithmetic over
 * `chrom_offset` and contig lengths, which is the same arithmetic a metacool
 * uses one level below its genomes. So it is read natively rather than dressed
 * up as a one-genome metacool — no invented `/genomes` row, no fabricated
 * `genome_id` column, and no flag downstream to remember which of the two it is
 * looking at. `mc.genomes` is `null`, and every genome accessor answers with
 * emptiness rather than with a fiction.
 *
 * The oracle is `test/golden/plain_cool.json`, generated by `cooler` itself.
 * Its `info` block is cooler's raw dict, so the assertions below read the keys
 * the golden actually carries rather than the metacool-shaped ones in
 * `open.test.ts`.
 */

import { describe, expect, it } from 'vitest'

import { UNBINNED_NAME } from '../../src/constants'
import { ViewerError } from '../../src/errors'
import { MetaCooler } from '../../src/metacooler/MetaCooler'
import { parseMetacoolerRange } from '../../src/metacooler/range'
import { LocalFileSource } from '../../src/sources/LocalFileSource'
import { firstEntry } from '../../src/ui/FilePicker'
import { fixturePath, loadGolden } from './_golden'

const COOL = loadGolden('plain_cool.json')
const MCOOL = loadGolden('plain_mcool.json')

async function open(fixture: string, uri = fixture): Promise<MetaCooler> {
  const path = fixturePath(fixture)
  const source = await LocalFileSource.open(path)
  return MetaCooler.open(uri.replace(fixture, path), source)
}

async function withCool<T>(body: (mc: MetaCooler) => T | Promise<T>, uri = 'plain.cool'): Promise<T> {
  const mc = await open(uri.split('::')[0], uri)
  try {
    return await body(mc)
  } finally {
    mc.close()
  }
}

describe('a plain cool opens natively', () => {
  it('is a cool, with no genome layer at all', async () => {
    await withCool((mc) => {
      expect(mc.layout.kind).toBe('cool')
      expect(mc.hasGenomes).toBe(false)
      expect(mc.genomes).toBeNull()
      expect(mc.nGenomes).toBe(0)
      expect(mc.genomeNames).toEqual([])
      // Empty, not zero-filled: a zero would be a genome id pointing at a
      // genome that does not exist, and aggregation could not tell the
      // difference.
      expect(mc.contigGenomeIds.length).toBe(0)
      expect(mc.displayGenomes()).toEqual([])
      expect(mc.unassignedStats()).toBeNull()
    })
  })

  it('reads its chroms as the contig table', async () => {
    await withCool((mc) => {
      expect(mc.chromnames).toEqual(COOL.chromnames)
      expect(mc.nContigs).toBe(COOL.chromnames.length)
      expect(Object.fromEntries(mc.chromsizes)).toEqual(COOL.chromsizes)
      expect(mc.contigs.columns).toEqual(expect.arrayContaining(['name', 'length']))
      expect(mc.contigs.columns).not.toContain('genome_id')
    })
  })

  it('agrees with cooler about shape, bin size and count dtype', async () => {
    await withCool((mc) => {
      expect(mc.shape).toEqual(COOL.shape)
      expect(mc.nBins).toBe(COOL.shape[0])
      expect(mc.binsize).toBe(COOL.binsize)
      expect(mc.countKind).toBe(COOL.count_dtype_kind)
      expect(mc.storageMode).toBe(COOL.info['storage-mode'])
    })
  })

  it('reports the cooler format rather than a null one', async () => {
    await withCool((mc) => {
      // `metacooler-format` is absent here; the file's own `format` answers
      // the same question and is what the info panel shows.
      expect(mc.info.format).toBe('HDF5::Cooler')
      expect(mc.info['format-version']).toBe(COOL.info['format-version'])
      expect(mc.info.ncontigs).toBe(COOL.info.nchroms)
      expect(mc.info.ngenomes).toBeNull()
    })
  })

  it('resolves regions with cooler semantics', async () => {
    await withCool((mc) => {
      const first = COOL.chromnames[0] as string
      const [lo, hi] = mc.extent(first)
      expect(lo).toBe(0)
      expect(hi).toBe(Math.ceil((COOL.chromsizes[first] as number) / COOL.binsize))
      expect(mc.offset(first)).toBe(0)
      expect(mc.contigExtent(first)).toEqual([lo, hi])
      // A window inside a chromosome, half-open and 0-based, as cooler parses it.
      expect(mc.extent(`${first}:2,000-5000`)).toEqual([2, 5])
    })
  })

  it('draws the same matrices cooler does', async () => {
    await withCool(async (mc) => {
      for (const oracle of COOL.matrices as Array<Record<string, any>>) {
        const dense = await mc.matrix({ rows: oracle.rows, cols: oracle.cols })
        expect(dense.nrows).toBe(oracle.values.length)
        expect(dense.ncols).toBe(oracle.values[0].length)
        const actual = Array.from({ length: dense.nrows }, (_, r) =>
          Array.from(dense.values.slice(r * dense.ncols, (r + 1) * dense.ncols)),
        )
        expect(actual, `matrix ${oracle.id}`).toEqual(oracle.values)
      }
    })
  })

  it('resolves a range through the same entry point the worker uses', async () => {
    await withCool((mc) => {
      const first = COOL.chromnames[0] as string
      const parsed = parseMetacoolerRange(mc, first)
      // `kind: 'contig'` and not `'genome'`: with no genome table there is
      // nothing for a label to match at the genome level, so every label is a
      // contig or an error.
      expect(parsed.kind).toBe('contig')
      expect(parsed.label).toBe(first)
      expect(parsed.extent).toEqual(mc.contigExtent(first))

      const windowed = parseMetacoolerRange(mc, `${first}:1000-4000`)
      expect(windowed.extent).toEqual([1, 4])
    })
  })

  it('names the contigs when a label matches nothing', async () => {
    await withCool((mc) => {
      let thrown: unknown
      try {
        parseMetacoolerRange(mc, 'no_such_thing')
      } catch (error) {
        thrown = error
      }
      expect(thrown).toBeInstanceOf(ViewerError)
      expect((thrown as ViewerError).code).toBe('unknown-label')
      expect((thrown as ViewerError).message).toContain(COOL.chromnames[0])
    })
  })

  it('rolls a block up to contig level without a genome layer', async () => {
    await withCool(async (mc) => {
      // The first four chromosomes, summed to one cell each: contig level is
      // the only aggregation a cooler has, and it needs nothing but chrom_offset.
      const rows = mc.contigExtent(COOL.chromnames[0] as string)
      const upto = mc.contigExtent(COOL.chromnames[3] as string)
      const dense = await mc.matrix({ rows: [rows[0], upto[1]] })
      const rolled = mc.aggregate(dense, 'contig')
      expect(rolled.nrows).toBe(4)
      expect(rolled.ncols).toBe(4)
      // The ids are contig indices — the file's own, not renumbered.
      expect(Array.from(rolled.rowIds)).toEqual([0, 1, 2, 3])
      expect(Array.from(rolled.colIds)).toEqual([0, 1, 2, 3])
      expect(rolled.level).toBe('contig')
      // Under `symmetric-upper` an on-diagonal block is a mirror of a
      // half-stored triangle, so the roll-up folds it before summing —
      // otherwise every within-contig off-diagonal pixel would be counted
      // twice. The first cell is therefore the *upper triangle* of contig 0's
      // own square, which is what `metacooler aggregate` reports.
      const width = dense.ncols
      let folded = 0
      for (let r = rows[0]; r < rows[1]; r++) {
        for (let c = r; c < rows[1]; c++) folded += dense.values[r * width + c]
      }
      expect(rolled.values[0]).toBeCloseTo(folded, 3)
      // And the result is symmetric, as the block it came from is.
      for (let r = 0; r < rolled.nrows; r++) {
        for (let c = 0; c < rolled.ncols; c++) {
          expect(rolled.values[r * rolled.ncols + c]).toBeCloseTo(
            rolled.values[c * rolled.ncols + r],
            6,
          )
        }
      }
    })
  })

  it('refuses a genome by name, because there are none', async () => {
    await withCool((mc) => {
      expect(mc.hasGenome('unknown')).toBe(false)
      expect(mc.hasGenome(UNBINNED_NAME)).toBe(false)
      expect(() => mc.genomeExtent('unknown')).toThrow(ViewerError)
    })
  })
})

describe('an mcool is a ladder of coolers', () => {
  it('refuses its root by naming the resolutions', async () => {
    let thrown: unknown
    try {
      const mc = await open('plain.mcool')
      mc.close()
    } catch (error) {
      thrown = error
    }
    expect(thrown).toBeInstanceOf(ViewerError)
    const err = thrown as ViewerError
    // Not `variable-bins`: an mcool root carries no bin-size attribute, and the
    // old order refused it as a fragment-level file and told the user to binnify
    // a file that is already binned three ways.
    expect(err.code).toBe('mcool-root')
    expect(err.detail['entries']).toEqual(MCOOL.entries)
    expect(err.detail['group']).toBe('resolutions')
    for (const resolution of MCOOL.entries as string[]) {
      expect(err.message).toContain(`/resolutions/${resolution}`)
    }
  })

  it('opens each resolution as an ordinary cooler', async () => {
    for (const resolution of MCOOL.entries as string[]) {
      const golden = (MCOOL.entry_golden as Record<string, any>)[resolution]
      await withCool((mc) => {
        expect(mc.layout.kind).toBe('cool')
        expect(mc.binsize).toBe(golden.binsize)
        expect(mc.shape).toEqual(golden.shape)
        expect(mc.chromnames).toEqual(golden.chromnames)
        expect(mc.hasGenomes).toBe(false)
      }, `plain.mcool::resolutions/${resolution}`)
    }
  })

  it('lands a third of the way up its resolutions, whatever order HDF5 lists them in', () => {
    // HDF5 lists group members lexicographically, which puts `1000` before
    // `500` and `10000` before `5000`. The names are bin sizes, so the ladder
    // is ordered by number — 500, 1000, 5000, 10000 — and the landing rung is
    // the second of the four, not the finest.
    const err = new ViewerError('mcool-root', 'No cooler at root', {
      entries: ['10000', '1000', '500', '5000'],
      group: 'resolutions',
    })
    expect(firstEntry(err)).toEqual({ group: 'resolutions', entry: '1000' })
    // Six or seven resolutions: the third.
    const six = new ViewerError('mcool-root', 'No cooler at root', {
      entries: ['1000', '2000', '5000', '10000', '50000', '100000'],
      group: 'resolutions',
    })
    expect(firstEntry(six)).toEqual({ group: 'resolutions', entry: '5000' })
  })

  it('offers its resolutions in numeric order', async () => {
    await withCool((mc) => {
      expect(mc.entries).toEqual([...mc.entries].sort((a, b) => Number(a) - Number(b)))
    }, 'plain.mcool::resolutions/1000')
  })

  it('knows its siblings, so the ladder can be offered', async () => {
    await withCool((mc) => {
      expect(mc.entries).toEqual(MCOOL.entries)
      expect(mc.entryGroup).toBe('resolutions')
    }, 'plain.mcool::resolutions/1000')
  })

  it('has short last bins at coarse resolutions, and counts them', async () => {
    // 5 kb over contigs that are not multiples of 5 kb: the case that exercises
    // the ceil in `binsInContig` and the min in `binEnd`, which 1 kb does not.
    await withCool((mc) => {
      const golden = (MCOOL.entry_golden as Record<string, any>)['5000']
      expect(mc.nBins).toBe(golden.shape[0])
      for (const name of mc.chromnames) {
        const [lo, hi] = mc.contigExtent(name)
        expect(hi - lo).toBe(Math.ceil((mc.chromsizes.get(name) as number) / 5000))
      }
    }, 'plain.mcool::resolutions/5000')
  })
})

describe('balanced counts', () => {
  it('multiplies each cell by its two bin weights, as cooler does', async () => {
    // `plain.mcool` ships a /bins/weight column; `plain.cool` does not.
    await withCool(async (mc) => {
      expect(mc.hasWeights).toBe(true)
      const rows: [number, number] = [0, 24]
      const raw = await mc.matrix({ rows })
      const balanced = await mc.matrix({ rows, balance: true })

      const weights = mc.handle.readNumeric('bins/weight', rows[0], rows[1])
      const width = raw.ncols
      for (let r = 0; r < raw.nrows; r++) {
        for (let c = 0; c < width; c++) {
          const expected = raw.values[r * width + c] * weights[r] * weights[c]
          const actual = balanced.values[r * width + c]
          if (Number.isNaN(expected)) expect(Number.isNaN(actual)).toBe(true)
          else expect(actual).toBeCloseTo(expected, 5)
        }
      }
      // And it is a real normalisation, not a no-op: some cell changed.
      expect(Array.from(balanced.values)).not.toEqual(Array.from(raw.values))
    }, 'plain.mcool::resolutions/1000')
  })

  it('says so rather than silently returning raw counts when there are none', async () => {
    await withCool(async (mc) => {
      expect(mc.hasWeights).toBe(false)
      await expect(mc.matrix({ rows: [0, 10], balance: true })).rejects.toThrow(/no \/bins\/weight/)
    })
  })
})

describe('a dropped bin does not blank the chromosome it sits in', () => {
  it('skips NaN when rolling up to contig level', async () => {
    await withCool(async (mc) => {
      const rows: [number, number] = [0, mc.nBins]
      const balanced = await mc.matrix({ rows, balance: true })
      const rolled = mc.aggregate(balanced, 'contig')
      // The fixture's weights include NaNs, so the bin-level block has some;
      // rolled up, a contig is only NaN when *every* one of its cells was.
      const nanCells = Array.from(balanced.values).filter((v) => Number.isNaN(v)).length
      expect(nanCells).toBeGreaterThan(0)
      const nanContigs = Array.from(rolled.values).filter((v) => Number.isNaN(v)).length
      expect(nanContigs).toBeLessThan(rolled.values.length)
      expect(Array.from(rolled.values).some((v) => v > 0)).toBe(true)
    }, 'plain.mcool::resolutions/1000')
  })
})
