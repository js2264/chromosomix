/**
 * Build `src/analysis/wasm/yapc.generated.ts` from `src/analysis/wasm/yapc.c`.
 *
 * yapc's scan of a window — pieces, pooling, the 456-tap convolution, the
 * concave mask and the concave regions (§18.8) — compiled to WebAssembly with
 * SIMD and committed as base64 in a TypeScript file, as the correlation kernel
 * (`scripts/build-gram-wasm.mjs`) and Boost-HiC's Floyd–Warshall
 * (`scripts/build-floyd-wasm.mjs`) are, so the app builds with no C toolchain and
 * loads no file at run time: only whoever changes the C needs clang (with the
 * `wasm32` target) and lld. Re-run with `npm run wasm:yapc` after changing it;
 * `test/unit/yapc-kernel.test.ts` fails until you do, since the generated file
 * records the hash of the source it was built from.
 *
 * Two flags beyond the other kernels': `-ffp-contract=off`, since the module is
 * held to the TypeScript bit for bit and a fused multiply-add rounds once where
 * the TypeScript rounds twice; and `-mbulk-memory`, so the fills and copies
 * clang recognises become `memory.fill` and `memory.copy` rather than calls to a
 * `memset` that a module with no C library does not have.
 *
 *   npm run wasm:yapc
 */

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'src/analysis/wasm/yapc.c')
const target = join(root, 'src/analysis/wasm/yapc.generated.ts')

// clang looks for the linker as `wasm-ld`, which is lld under another name and
// is not always installed as one: a symlink on a private PATH entry answers it.
const work = mkdtempSync(join(tmpdir(), 'yapc-wasm-'))
try {
  const lld = execFileSync('which', ['lld'], { encoding: 'utf8' }).trim()
  symlinkSync(lld, join(work, 'wasm-ld'))
} catch {
  // A `wasm-ld` already on PATH is used as it is.
}
const literal = (bytes) =>
  (bytes.toString('base64').match(/.{1,100}/g) ?? [])
    .map((line, i, all) => `  '${line}'${i === all.length - 1 ? '' : ' +'}`)
    .join('\n')
try {
  const out = join(work, 'yapc.wasm')
  execFileSync(
    'clang',
    [
      '--target=wasm32',
      '-O3',
      '-msimd128',
      '-mbulk-memory',
      '-ffp-contract=off',
      '-nostdlib',
      '-Wl,--no-entry',
      '-Wl,--import-memory',
      '-Wl,--export-dynamic',
      '-o',
      out,
      source,
    ],
    { stdio: 'inherit', env: { ...process.env, PATH: `${work}:${process.env.PATH ?? ''}` } },
  )
  const bytes = readFileSync(out)
  const hash = createHash('sha256').update(readFileSync(source)).digest('hex')
  writeFileSync(
    target,
    `/**
 * Generated by \`npm run wasm:yapc\` from \`yapc.c\` — do not edit.
 *
 * yapc's scan of a window (§18.8) as a WebAssembly module with SIMD
 * (${bytes.length.toLocaleString('en')} bytes), base64, so the app carries it with
 * no loader and no C toolchain.
 */

/** The SHA-256 of the \`yapc.c\` this was built from, which a test compares. */
export const YAPC_SOURCE_SHA256 = '${hash}'

export const YAPC_WASM_BASE64 =
${literal(bytes)}
`,
  )
  console.log(`wrote ${target} (${bytes.length} bytes of wasm, source ${hash.slice(0, 12)})`)
} finally {
  rmSync(work, { recursive: true, force: true })
}
